// ── Search function ──────────────────────────────────────

export function searchKnowledge(query: string): KnowledgeEntry[] {
  const q = query.toLowerCase()
  const scored = TAX_KNOWLEDGE.map(entry => {
    let score = 0
    for (const kw of entry.keywords) {
      if (q.includes(kw.toLowerCase())) score += 2
      if (kw.toLowerCase().includes(q.split(' ')[0])) score += 1
    }
    if (entry.content.toLowerCase().includes(q)) score += 1
    return { entry, score }
  })
  return scored.filter(x => x.score > 0).sort((a, b) => b.score - a.score).map(x => x.entry)
}
